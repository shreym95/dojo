test('voice module in the repo matches shared/voice/*.md exactly', () => {
  const onDisk = fs.readFileSync(path.join(REPO, VOICE_MODULE), 'utf8');
  assert.equal(onDisk, renderVoiceModule((rel) => fs.readFileSync(path.join(REPO, rel), 'utf8')));
  for (const level of ['subtle', 'medium', 'full']) {
    const md = fs.readFileSync(path.join(REPO, `shared/voice/${level}.md`), 'utf8').trim();
    const line = onDisk.split('\n').find((l) => l.startsWith(`  ${level}: `));
    assert.equal(JSON.parse(line.slice(`  ${level}: `.length, -1)), md, `${level} rules are the file's text`);
  }
});

test('check mode covers the voice module: missing, clean, drifted; write repairs; skipped without mods/', async (t) => {
  const plain = fixtureTree();
  const root = fixtureTree();
  t.after(() => { fs.rmSync(plain, { recursive: true, force: true }); fs.rmSync(root, { recursive: true, force: true }); });
  fs.mkdirSync(path.join(root, 'mods'), { recursive: true });
  const target = path.join(root, VOICE_MODULE);

  // no mods/ folder: nothing extra is generated or expected
  await run({ root: plain });
  assert.ok(!fs.existsSync(path.join(plain, 'mods')));
  assert.equal((await run({ root: plain, check: true })).ok, true);

  await run({ root });
  fs.rmSync(target);
  let r = await run({ root, check: true });
  assert.deepEqual(r.problems, [`missing: ${VOICE_MODULE}`]);
  assert.ok(!fs.existsSync(target), 'check does not write');

  const w = await run({ root });
  assert.deepEqual(w.written, [VOICE_MODULE]);
  assert.equal(fs.readFileSync(target, 'utf8'), renderVoiceModule(readFile));
  assert.deepEqual((await run({ root, check: true })).problems, []);

  fs.appendFileSync(target, '// tampered\n');
  r = await run({ root, check: true });
  assert.deepEqual(r.problems, [`drifted: ${VOICE_MODULE}`]);

  // editing a voice file without rebuilding is drift too
  await run({ root });
  fs.writeFileSync(path.join(root, 'shared/voice/subtle.md'), 'CHANGED-SUBTLE');
  assert.deepEqual((await run({ root, check: true })).problems, [`drifted: ${VOICE_MODULE}`]);
});

